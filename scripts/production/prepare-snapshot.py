#!/usr/bin/env python3
"""Validate/copy an OFFLINE appdata snapshot; never inspect the live node.

A schema-68 marker is normalized only when its complete SQLite structure matches
schema 69 generated by this checkout's models. Structural ambiguity fails closed.
"""
import argparse
import datetime
from contextlib import closing
import hashlib
import json
import os
from pathlib import Path
import re
import shutil
import sqlite3
import stat
import uuid

ROOT = Path(__file__).resolve().parents[2]
LIVE = Path('/opt/apps/wbe/node1')
BACKUPS = Path('/opt/apps/wbe/backups')


class PreparationError(RuntimeError):
    pass


def reject_links(path):
    path = Path(os.path.abspath(path))
    for part in (path, *path.parents):
        if part.is_symlink():
            raise PreparationError('Symbolic links are not allowed')
    return path


def digest(path):
    with path.open('rb') as stream:
        return hashlib.file_digest(stream, 'sha256').hexdigest()


def readonly(path):
    conn = sqlite3.connect(path.as_uri() + '?mode=ro', uri=True)
    conn.execute('PRAGMA query_only=ON')
    conn.execute('BEGIN')
    return conn


def sql_tokens(sql):
    # Keep literals and quoted identifiers byte-for-byte; ignore only formatting
    # and unquoted SQL case. Do not silently remove constraints or expressions.
    return tuple(token if token.startswith(('"', "'", '`', '[')) else token.lower()
                 for token in re.findall(r"'(?:''|[^'])*'|\"(?:\"\"|[^\"])*\"|`[^`]*`|\[[^\]]*\]|\w+|[^\s]", sql or ''))


def structure(conn):
    quote = lambda name: '"' + name.replace('"', '""') + '"'
    objects = conn.execute("SELECT type,name,tbl_name,sql FROM sqlite_master WHERE name != 'sqlite_sequence' AND sql IS NOT NULL ORDER BY type,name").fetchall()
    result = {'objects': [(kind, name, table, sql_tokens(sql)) for kind, name, table, sql in objects], 'tables': {}}
    for kind, name, _, _ in objects:
        if kind != 'table':
            continue
        indexes = []
        for _, idx, unique, origin, partial in conn.execute('PRAGMA index_list(' + quote(name) + ')'):
            indexes.append((idx, unique, origin, partial,
                            tuple(conn.execute('PRAGMA index_xinfo(' + quote(idx) + ')'))))
        result['tables'][name] = {
            'columns': list(conn.execute('PRAGMA table_xinfo(' + quote(name) + ')')),
            'foreign_keys': sorted(conn.execute('PRAGMA foreign_key_list(' + quote(name) + ')')),
            'indexes': sorted(indexes),
        }
    return result


def canonical_structure():
    from sqlalchemy import create_engine
    from globaleaks import DATABASE_VERSION, models
    if DATABASE_VERSION != 69:
        raise PreparationError('This tool is pinned to application schema 69')
    engine = create_engine('sqlite:///:memory:')
    try:
        models.Base.metadata.create_all(engine)
        raw = engine.raw_connection()
        try:
            return structure(raw)
        finally:
            raw.close()
    finally:
        engine.dispose()


def validate(conn, canonical):
    if conn.execute('PRAGMA integrity_check').fetchall() != [('ok',)]:
        raise PreparationError('SQLite integrity check failed')
    if conn.execute('PRAGMA foreign_key_check').fetchone():
        raise PreparationError('SQLite foreign key check failed')
    if structure(conn) != canonical:
        raise PreparationError('Complete SQLite structure differs from canonical schema 69; offline migration/review required')
    markers = conn.execute("SELECT tid,value FROM config WHERE var_name='version_db' ORDER BY tid").fetchall()
    if not markers or sum(tid == 1 for tid, _ in markers) != 1:
        raise PreparationError('Root schema marker missing or duplicated')
    for _, value in markers:
        try:
            marker = json.loads(value)
        except (ValueError, TypeError):
            raise PreparationError('Invalid schema marker') from None
        if type(marker) is not int or marker not in (68, 69):
            raise PreparationError('Only schema markers 68 and 69 are accepted')
    if conn.execute('SELECT count(*) FROM internalfile WHERE new=1').fetchone()[0]:
        raise PreparationError('Pending attachment delivery prevents offline preparation')
    return markers


def inventory(source):
    files = {}
    directories = []
    for parent, dirs, names in os.walk(source, followlinks=False):
        for name in dirs + names:
            path = Path(parent) / name
            mode = path.lstat().st_mode
            if not (stat.S_ISDIR(mode) or stat.S_ISREG(mode)):
                raise PreparationError('Snapshot contains a symlink or special file')
            relative = path.relative_to(source)
            if stat.S_ISDIR(mode):
                directories.append(relative)
            else:
                files[relative] = digest(path)
    for suffix in ('-wal', '-shm', '-journal'):
        if Path('globaleaks.db' + suffix) in files:
            raise PreparationError('SQLite sidecars present; provide a frozen clean snapshot')
    return directories, files


def prepare(source, root=ROOT):
    root = reject_links(Path(root))
    source = Path(os.path.abspath(source))
    if source == LIVE or LIVE in source.parents:
        raise PreparationError('Live node access is forbidden')
    source = reject_links(source)
    allowed = (root / '.local/imports', BACKUPS)
    if not any(base in source.parents for base in allowed):
        raise PreparationError('Source must be a staged appdata directory under approved imports/backups')
    if not source.is_dir() or not (source / 'globaleaks.db').is_file():
        raise PreparationError('Source must contain globaleaks.db')
    canonical = canonical_structure()
    directories, before = inventory(source)
    database = source / 'globaleaks.db'
    with closing(readonly(database)) as conn:
        markers = validate(conn, canonical)
    parent = reject_links(root / '.local/production/imports')
    parent.mkdir(mode=0o700, parents=True, exist_ok=True)
    # Verify and protect the production subtree; do not change source modes.
    for directory in (root / '.local/production', parent):
        directory.chmod(0o700)
    name = datetime.datetime.now(datetime.timezone.utc).strftime('%Y%m%dT%H%M%SZ') + '-' + uuid.uuid4().hex[:12]
    destination = parent / name
    destination.mkdir(mode=0o700, exist_ok=False)
    try:
        appdata = destination / 'appdata'
        appdata.mkdir(mode=0o700)
        for relative in directories:
            (appdata / relative).mkdir(mode=0o700, parents=True, exist_ok=True)
        for relative, expected in before.items():
            copied = appdata / relative
            # Exclusive files and no preserved links, modes, devices or owners.
            with (source / relative).open('rb') as original, copied.open('xb') as target:
                os.chmod(copied, 0o600)
                shutil.copyfileobj(original, target)
            if digest(copied) != expected:
                raise PreparationError('Source changed during copy')
        copied_db = appdata / 'globaleaks.db'
        with closing(sqlite3.connect(copied_db)) as conn, conn:
            conn.execute('BEGIN IMMEDIATE')
            validate(conn, canonical)
            for tid, value in markers:
                if json.loads(value) == 68:
                    conn.execute("UPDATE config SET value=? WHERE tid=? AND var_name='version_db' AND value=?", ('69', tid, value))
            validate(conn, canonical)
        # All files must remain unchanged, including the original database.
        _, after = inventory(source)
        if before != after:
            raise PreparationError('Source changed; prepared output is invalid')
        metadata = {'status': 'prepared-offline-schema69', 'application_schema': 69,
                    'source_database_sha256': before[Path('globaleaks.db')],
                    'prepared_database_sha256': digest(copied_db),
                    'normalized_marker_count': sum(json.loads(value) == 68 for _, value in markers),
                    'verified_files': len(before), 'complete_canonical_structure_match': True,
                    'source_unchanged': True}
        manifest = destination / 'preparation.json'
        with manifest.open('x') as stream:
            os.chmod(manifest, 0o600)
            json.dump(metadata, stream, indent=2)
            stream.write('\n')
        return destination
    except BaseException:
        shutil.rmtree(destination)
        raise


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--source', required=True, help='Frozen staged appdata directory, never a live node')
    args = parser.parse_args()
    try:
        print(prepare(args.source))
    except PreparationError as error:
        parser.exit(1, 'Preparation refused: ' + str(error) + '\n')
    except Exception as error:
        parser.exit(1, 'Preparation failed (' + type(error).__name__ + '); no valid output retained\n')


if __name__ == '__main__':
    main()
